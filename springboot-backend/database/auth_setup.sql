-- Run in TEJA_DATA_QUALITY_DB.DQ using your Snowflake SQL worksheet.
-- One additional application table; existing six DQ tables are unchanged.
CREATE TABLE IF NOT EXISTS USERS (
    USER_ID VARCHAR(36) NOT NULL,
    FULL_NAME VARCHAR(120) NOT NULL,
    EMAIL VARCHAR(255) NOT NULL,
    PASSWORD_HASH VARCHAR(255) NOT NULL,
    USER_ROLE VARCHAR(20) NOT NULL DEFAULT 'OPERATOR',
    STATUS VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    CREATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_USERS PRIMARY KEY (USER_ID),
    CONSTRAINT UQ_USERS_EMAIL UNIQUE (EMAIL)
);

-- Optional: after registering the first account, verify it is ADMIN.
SELECT USER_ID, FULL_NAME, EMAIL, USER_ROLE, STATUS, CREATED_AT
FROM USERS
ORDER BY CREATED_AT;
